import { drizzle } from "drizzle-orm/node-postgres";
import { Pool } from "pg";
import * as schema from "./schema";

const databaseUrl = process.env.DATABASE_URL;

// MOCK MODE: Prevent crash when DATABASE_URL is missing during UI testing
if (!databaseUrl && process.env.NODE_ENV !== "production") {
  console.warn("⚠️ Mock Mode: DATABASE_URL is missing. Database operations will fail, but UI can be tested with mocks.");
} else if (!databaseUrl) {
  throw new Error("DATABASE_URL is required");
}

const globalForDb = globalThis as typeof globalThis & {
  __arenaNextJsPostgresqlPool?: Pool;
};

export const pool =
  globalForDb.__arenaNextJsPostgresqlPool ??
  new Pool({
    connectionString: databaseUrl || "postgres://localhost:5432/mock",
  });

if (process.env.NODE_ENV !== "production") {
  globalForDb.__arenaNextJsPostgresqlPool = pool;
}

export const db = drizzle(pool, { schema });
