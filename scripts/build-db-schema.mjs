/**
 * Builds the deployment schema.
 *
 * GlucoPlate runs one Postgres database shared by all four services, but
 * each service keeps its own `prisma/schema.prisma` so that it only ever
 * generates a client for the models it owns. That means the database itself
 * needs a schema that contains every model.
 *
 * This script concatenates the service schemas into `prisma/schema.prisma`,
 * which is the schema `prisma db push` uses. It is generated rather than
 * hand-written so the two can never drift apart.
 *
 *   npm run db:schema
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The services, in the order their tables are created. */
const SERVICES = [
  { name: "svc-auth", dir: "svc-auth" },
  { name: "svc-catalog", dir: "svc-catalog" },
  { name: "svc-planner", dir: "svc-planner" },
  { name: "svc-health", dir: "svc-health" },
];

/**
 * Pulls the `model` and `enum` blocks out of a Prisma schema.
 *
 * The blocks are found by their opening keyword and closed with a brace
 * count, so comments and formatting inside them are preserved exactly.
 */
function extractBlocks(source) {
  const blocks = [];
  const pattern = /^(model|enum)\s+(\w+)\s*\{/gm;

  let match;
  while ((match = pattern.exec(source)) !== null) {
    const start = match.index;
    let depth = 0;
    let index = source.indexOf("{", start);

    for (; index < source.length; index += 1) {
      const char = source[index];
      if (char === "{") depth += 1;
      else if (char === "}") {
        depth -= 1;
        if (depth === 0) break;
      }
    }

    blocks.push({
      kind: match[1],
      name: match[2],
      text: source.slice(start, index + 1),
    });

    pattern.lastIndex = index + 1;
  }

  return blocks;
}

const header = `// GlucoPlate — the deployment schema.
//
// GENERATED by \`npm run db:schema\`. Do not edit it by hand.
//
// GlucoPlate runs ONE Postgres database shared by all four services. Each
// service still owns its own \`prisma/schema.prisma\` and generates a client
// for only the models it owns, so a service physically cannot read or write
// another service's tables. This file exists so that \`prisma db push\` can
// create every table in the shared database.
//
//   DATABASE_URL        pooled connection used at runtime
//   DIRECT_DATABASE_URL direct connection used by schema operations
//
// The table owners are:
//
//   User, Payment                 -> svc-auth
//   Dish                          -> svc-catalog
//   MealPlan, MealPlanItem        -> svc-planner
//   WeightLog, WeightTarget       -> svc-health

generator client {
  provider = "prisma-client-js"
  output   = "../generated/prisma"
}

datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  directUrl = env("DIRECT_DATABASE_URL")
}
`;

const seen = new Set();
const sections = [];

for (const service of SERVICES) {
  const schemaPath = join(root, "apps", service.dir, "prisma", "schema.prisma");
  if (!existsSync(schemaPath)) {
    console.log(`  skipped ${service.name} (no schema)`);
    continue;
  }

  const blocks = extractBlocks(readFileSync(schemaPath, "utf8"));

  for (const block of blocks) {
    if (seen.has(block.name)) {
      throw new Error(
        `Two services both define "${block.name}". Each model must have one owner.`,
      );
    }
    seen.add(block.name);
  }

  const body = blocks.map((block) => block.text).join("\n\n");
  sections.push(
    `// ── ${service.name} ${"─".repeat(Math.max(0, 62 - service.name.length))}\n\n${body}`,
  );

  console.log(
    `  ${service.name.padEnd(14)} ${blocks.length} model(s): ${blocks.map((b) => b.name).join(", ")}`,
  );
}

const target = join(root, "prisma", "schema.prisma");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${header}\n${sections.join("\n\n")}\n`, "utf8");

console.log(`\nWrote prisma/schema.prisma with ${seen.size} model(s).`);
